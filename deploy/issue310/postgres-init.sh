#!/bin/sh
set -eu

: "${WA310_MIGRATION_PASSWORD:?}"
: "${WA310_API_PASSWORD:?}"
: "${WA310_SENDER_PASSWORD:?}"
: "${WA310_WEBHOOK_PASSWORD:?}"

psql -v ON_ERROR_STOP=1 \
  --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" \
  -v mig="$WA310_MIGRATION_PASSWORD" \
  -v api="$WA310_API_PASSWORD" \
  -v sender="$WA310_SENDER_PASSWORD" \
  -v webhook="$WA310_WEBHOOK_PASSWORD" <<'SQL'
SELECT format('CREATE ROLE wa310_migrate LOGIN PASSWORD %L NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS', :'mig') \gexec
SELECT format('CREATE ROLE wa310_api LOGIN PASSWORD %L NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS', :'api') \gexec
SELECT format('CREATE ROLE wa310_sender LOGIN PASSWORD %L NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS', :'sender') \gexec
SELECT format('CREATE ROLE wa310_webhook LOGIN PASSWORD %L NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS', :'webhook') \gexec
ALTER DATABASE vaylet_wa310 OWNER TO wa310_migrate;
ALTER SCHEMA public OWNER TO wa310_migrate;
REVOKE ALL ON DATABASE vaylet_wa310 FROM PUBLIC;
REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT CONNECT ON DATABASE vaylet_wa310 TO wa310_migrate, wa310_api, wa310_sender, wa310_webhook;
GRANT USAGE, CREATE ON SCHEMA public TO wa310_migrate;
SQL
