export function analyticsCopy(locale: DashboardLocale) {
  return copy[locale];
}

export function analyticsValidationCopy(
  locale: DashboardLocale,
  kind: AnalyticsPeriodValidation["kind"],
): string {
  const t = analyticsCopy(locale);
  if (kind === "too-long") return t.periodTooLong;
  if (kind === "reversed") return t.reversedPeriod;
  return t.invalidDate;
}

export function analyticsPeriodMessage(
  locale: DashboardLocale,
  validation: AnalyticsPeriodValidation,
  error: unknown,
  loading: boolean,
): string | null {
  const t = analyticsCopy(locale);
  if (validation.kind === "required") return t.periodRequired;
  if (validation.kind !== "valid") return analyticsValidationCopy(locale, validation.kind);
  if (loading) return t.loading;
  if (!error) return null;
  if (!(error instanceof DashboardApiError)) return t.errorGeneric;
  if (error.code === "COMPANY_ANALYTICS_TOO_LARGE") return t.groupTooLarge;
  if (error.kind === "auth") return t.errorAuth;
  if (error.kind === "mfa") return t.errorMfa;
  if (error.kind === "authorization") return t.errorAuthorization;
  if (error.kind === "entitlement") return t.errorEntitlement;
  if (error.kind === "validation") return t.errorValidation;
  if (error.kind === "malformed") return t.errorMalformed;
  if (error.kind === "network") return t.errorNetwork;
  return t.errorGeneric;
}
