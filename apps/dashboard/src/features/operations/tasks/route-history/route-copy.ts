export function routeCopy(locale: "en" | "ar") {
  return locale === "ar" ? ar : en;
}

export function sampleTime(
  value: string,
  locale: "en" | "ar",
  timezone: string,
) {
  return new Intl.DateTimeFormat(locale === "ar" ? "ar-JO" : "en-GB", {
    timeZone: timezone,
    hour: "2-digit",
    minute: "2-digit",
    second: "2-digit",
    hour12: false,
  }).format(new Date(value));
}
